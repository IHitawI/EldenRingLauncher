def names():
    # "Актуальная" всегда остаётся первой, остальные идут от новой версии
    # к старой: 1.16, 1.15, ... 1.0. Простая сортировка строк здесь неверна
    # (например, 1.9 оказалась бы выше 1.16).
    def version_key(name):
        if name.startswith("Актуальная версия"):
            return (1, ())
        number = name.split(" ", 1)[0]
        try:
            return (0, tuple(int(part) for part in number.split(".")))
        except ValueError:
            return (0, ())

    current = [name for name in VERSIONS if name.startswith("Актуальная версия")]
    historical = [name for name in VERSIONS if name not in current]
    historical.sort(key=lambda name: version_key(name)[1], reverse=True)
    return current + historical


def get(name):
    return VERSIONS.get(name)


def install_method(name):
    version = get(name) or {}
    return version.get("install_method", "steamcmd")
